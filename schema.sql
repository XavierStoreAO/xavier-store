create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'customer' check (role in ('admin','customer')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  price numeric(12,2) not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  category text,
  sizes text,
  image_url text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_area text not null,
  notes text,
  items jsonb not null,
  total numeric(12,2) not null check (total >= 0),
  status text not null default 'nova'
    check (status in ('nova','confirmada','em_entrega','concluida','cancelada')),
  created_at timestamptz not null default now()
);

create or replace function public.is_store_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;

create policy "profiles: user reads own profile"
on public.profiles for select to authenticated
using (id = auth.uid());

create policy "products: public reads active"
on public.products for select to anon, authenticated
using (active = true or public.is_store_admin());

create policy "products: admin inserts"
on public.products for insert to authenticated
with check (public.is_store_admin());

create policy "products: admin updates"
on public.products for update to authenticated
using (public.is_store_admin()) with check (public.is_store_admin());

create policy "products: admin deletes"
on public.products for delete to authenticated
using (public.is_store_admin());

create policy "orders: public creates order"
on public.orders for insert to anon, authenticated
with check (status = 'nova');

create policy "orders: admin reads"
on public.orders for select to authenticated
using (public.is_store_admin());

create policy "orders: admin updates"
on public.orders for update to authenticated
using (public.is_store_admin()) with check (public.is_store_admin());

